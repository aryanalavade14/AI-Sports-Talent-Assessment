import uuid
from datetime import datetime

from fastapi import APIRouter, Depends, File, Form, Response, UploadFile
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.test_submission import TestSubmission
from app.models.user import User
from app.schemas.sync import (
    SyncBatchRequest,
    SyncBatchResponse,
    SyncItemResult,
    SyncStatusOut,
)
from app.schemas.test import TestResultOut, TestType
from app.services import submission_service, sync_service
from app.services.submission_service import VideoInput
from app.utils.deps import get_athlete_for_user, get_current_user
from app.utils.errors import AppError

router = APIRouter(prefix="/api/sync", tags=["Offline Sync"])


@router.post("/submissions", response_model=SyncItemResult)
def sync_submission(
    response: Response,
    client_submission_id: uuid.UUID = Form(..., description="UUID generated by the mobile app"),
    athlete_id: uuid.UUID = Form(...),
    test_type: TestType = Form(...),
    video: UploadFile = File(...),
    recorded_at: datetime | None = Form(None),
    duration_seconds: float | None = Form(None),
    sensor_data: str | None = Form(None, description="JSON string"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Sync ONE offline test (with its video). Safe to call repeatedly with the same UUID."""
    result = sync_service.sync_one(
        db,
        current_user,
        client_submission_id=client_submission_id,
        athlete_id=athlete_id,
        test_type=test_type.value,
        recorded_at=recorded_at,
        duration_seconds=duration_seconds,
        sensor_data_raw=sensor_data,
        video=VideoInput(filename=video.filename or "", content_type=video.content_type, stream=video.file),
    )
    response.status_code = 201 if result.status == "created" else 200
    return result


@router.post("/batch", response_model=SyncBatchResponse)
def sync_batch(
    data: SyncBatchRequest, db: Session = Depends(get_db), current_user: User = Depends(get_current_user)
):
    """Sync many offline tests at once (JSON, videos as base64). Returns success/failure per item."""
    results = [sync_service.sync_batch_item(db, current_user, item) for item in data.items]
    return SyncBatchResponse(
        total=len(results),
        succeeded=sum(1 for r in results if r.status == "created"),
        duplicates=sum(1 for r in results if r.status == "duplicate"),
        failed=sum(1 for r in results if r.status == "failed"),
        results=results,
    )


@router.get("/status/{client_submission_id}", response_model=SyncStatusOut)
def sync_status(
    client_submission_id: uuid.UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    record = submission_service.get_sync_record(db, client_submission_id)
    if record is None:
        raise AppError(404, "Unknown client_submission_id")
    get_athlete_for_user(db, current_user, record.athlete_id)  # owner-or-admin

    submission = db.get(TestSubmission, record.submission_id) if record.submission_id else None
    return SyncStatusOut(
        client_submission_id=record.client_submission_id,
        status=record.status,
        attempts=record.attempts,
        submission_id=record.submission_id,
        submission_status=submission.status if submission else None,
        cheat_flag=submission.cheat_flag if submission else None,
        error_message=record.error_message,
        last_attempt_at=record.updated_at,
        result=TestResultOut.model_validate(submission.result) if submission and submission.result else None,
    )
