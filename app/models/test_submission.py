import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import JSON, BigInteger, Boolean, DateTime, Float, ForeignKey, String, Text, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base
from app.models.base_mixins import TimestampMixin, UUIDPrimaryKeyMixin

# Allowed values (kept as plain strings so Alembic migrations stay simple)
TEST_TYPES = ("vertical_jump", "sit_up")
STATUS_PENDING = "pending"
STATUS_PROCESSING = "processing"
STATUS_COMPLETED = "completed"
STATUS_FAILED = "failed"


class TestSubmission(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __test__ = False  # tell pytest this is not a test class

    __tablename__ = "test_submissions"

    # Idempotency key generated by the mobile app (UUID)
    client_submission_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, unique=True, index=True, nullable=True)

    athlete_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("athletes.id", ondelete="CASCADE"), index=True, nullable=False
    )
    test_type: Mapped[str] = mapped_column(String(30), nullable=False)  # vertical_jump | sit_up
    status: Mapped[str] = mapped_column(String(20), default=STATUS_PENDING, nullable=False)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Video metadata
    video_path: Mapped[str] = mapped_column(String(500), nullable=False)  # relative to UPLOAD_DIR
    video_original_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    video_content_type: Mapped[str | None] = mapped_column(String(100), nullable=True)
    video_size_bytes: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)
    video_duration_seconds: Mapped[float | None] = mapped_column(Float, nullable=True)
    recorded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Phone sensor data (accelerometer / gyroscope samples)
    sensor_data: Mapped[dict | None] = mapped_column(JSON, nullable=True)

    # Basic cheat detection output
    cheat_flag: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    cheat_reasons: Mapped[list | None] = mapped_column(JSON, nullable=True)

    athlete: Mapped["Athlete"] = relationship(back_populates="submissions")  # noqa: F821
    result: Mapped[Optional["TestResult"]] = relationship(  # noqa: F821
        back_populates="submission", uselist=False, cascade="all, delete-orphan"
    )
